"""The edge's DNS, derived from the product registry (EDGE-001, #3495, #3482).

Self-service used to end at the cluster boundary: a product's staging zone was a
hand-written line in ``networking.staging_zones`` and its ACME zone was never
probed. This module derives both from what the platform already holds:

- the registry (``infra/config/products.yaml``) says which products run in an env;
- each product's committed contract snapshot names its hostname there;
- ``infra/terraform/dns/zones.json`` is the GRANT: a hostname counts only if its
  apex is a Cloudflare zone the platform declares. A contract chooses a name
  inside a granted zone and never grants one (owner ruling 2026-11-13), so a
  snapshot alone cannot widen split DNS, the ACME probe or Cloudflare.

The result is written to ``infra/config/products/edge.json`` (``toolkit sync
edge-dns``) because its readers are not all Python: the ``coredns`` role and the
VPS play read it with ``lookup('file') | from_json``, like ``services.json``.
``make validate-sync`` fails when the committed file differs from the derivation.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Sequence
from pathlib import Path

import yaml

from toolkit.config.settings import PROJECT_ROOT
from toolkit.features.product_registry import load_registry

MANIFEST = PROJECT_ROOT / "infra" / "config" / "products" / "edge.json"
DNS_ZONES = PROJECT_ROOT / "infra" / "terraform" / "dns" / "zones.json"
COMMON = PROJECT_ROOT / "infra" / "config" / "values" / "common.yaml"
SNAPSHOT_DIR = PROJECT_ROOT / "infra" / "config" / "products" / "contracts"

#: The platform's wildcard staging zone: a product with no domain of its own takes one label under it.
WILDCARD_ZONE = "staging.kubelab.live"

_HEADER = (
    "Generated by `toolkit sync edge-dns` from infra/config/products.yaml, the contract snapshots, "
    "infra/terraform/dns/zones.json and networking.staging_zones. Do not edit: `make validate-sync` "
    "fails on any difference."
)


class EdgeDnsError(ValueError):
    """A registered hostname the edge cannot serve. ``str()`` is ERROR / WHY / FIX."""

    def __init__(self, error: str, why: str, fix: str) -> None:
        super().__init__(f"ERROR: {error}\nWHY: {why}\nFIX: {fix}")


def _under(host: str, zone: str) -> bool:
    return host == zone or host.endswith(f".{zone}")


def apex_of(host: str, apexes: Iterable[str]) -> str | None:
    """The longest declared zone ``host`` is in, on a label boundary, or None."""
    matches = [apex for apex in apexes if _under(host, apex)]
    return max(matches, key=len) if matches else None


def staging_zone_for(host: str, declared: Sequence[str], apexes: Iterable[str]) -> str | None:
    """The split-DNS zone ``host`` needs, None when a declared zone already serves it.

    Raises ``EdgeDnsError`` for a host the edge cannot serve: one whose apex is not
    a zone in ``zones.json``. Shape rules (``staging.`` prefix, one label under the
    wildcard) are D8's, checked at render; this is the grant.
    """
    if any(_under(host, zone) and host != zone for zone in declared) or host in declared:
        return None
    if apex_of(host, apexes) is None:
        raise EdgeDnsError(
            f"staging hostname '{host}' is in no Cloudflare zone the platform declares",
            "a product's hostname gets split DNS, a certificate and a public record only inside a zone "
            "the platform granted; a contract chooses a name in a granted zone and cannot grant one (EDGE-001).",
            f"declare its apex in infra/terraform/dns/zones.json (an operator change, reviewed), "
            f"or use a name under a declared zone such as <label>.{WILDCARD_ZONE}",
        )
    return host


def granted_apexes(path: Path = DNS_ZONES) -> list[str]:
    """The Cloudflare zones the platform declares: the keys of ``zones.json``."""
    return list(json.loads(path.read_text(encoding="utf-8")))


def declared_staging_zones(path: Path = COMMON) -> list[str]:
    """The platform's own staging zones, ``networking.staging_zones`` in ``common.yaml``."""
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return [str(zone) for zone in (data.get("networking") or {}).get("staging_zones") or []]


def registered_hostnames(env: str, *, registry: Path | None = None, snapshot_dir: Path = SNAPSHOT_DIR) -> list[str]:
    """``hostnames.<env>`` of every registered product running in ``env``, in registry order.

    Only the registry decides who counts: a snapshot no entry claims, or one for a
    product with no lane in ``env``, contributes nothing. A product whose first
    snapshot has not landed yet has no hostname to contribute.
    """
    # Imported here: product_render imports product_guards, which imports this module.
    from toolkit.features.product_guards import declared_envs
    from toolkit.features.product_render import snapshot_path

    hosts = []
    for name, product in load_registry(registry).products.items():
        if not product.contract_managed or env not in declared_envs(product):
            continue
        snapshot = snapshot_path(name, env, snapshot_dir)
        if not snapshot.is_file():
            continue
        host = ((yaml.safe_load(snapshot.read_text(encoding="utf-8")) or {}).get("hostnames") or {}).get(env)
        if host:
            hosts.append(str(host))
    return hosts


def derive_staging_zones(
    declared: Sequence[str],
    apexes: Iterable[str],
    *,
    registry: Path | None = None,
    snapshot_dir: Path = SNAPSHOT_DIR,
) -> list[str]:
    """The declared zones, then each registered product's own staging zone; first position wins."""
    apexes = list(apexes)
    zones = list(dict.fromkeys(declared))
    for host in registered_hostnames("staging", registry=registry, snapshot_dir=snapshot_dir):
        zone = staging_zone_for(host, declared, apexes)
        if zone is not None and zone not in zones:
            zones.append(zone)
    return zones


def build_manifest() -> dict[str, object]:
    return {
        "_generated": _HEADER,
        "staging_zones": derive_staging_zones(declared_staging_zones(), granted_apexes()),
    }


def render_manifest() -> str:
    return json.dumps(build_manifest(), indent=2) + "\n"


def staging_zones(path: Path = MANIFEST) -> list[str]:
    """The effective staging zones, as the edge reads them: the committed manifest."""
    return [str(zone) for zone in json.loads(path.read_text(encoding="utf-8"))["staging_zones"]]


def sync(*, check: bool = False, path: Path = MANIFEST) -> int:
    """Write the manifest, or with ``check`` return 1 when the committed one differs."""
    rendered = render_manifest()
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    if check:
        return 0 if current == rendered else 1
    if current != rendered:
        path.write_text(rendered, encoding="utf-8")
    return 0
